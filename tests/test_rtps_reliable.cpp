std::vector<uint8_t> hex_to_bytes(std::string_view hex) {
    std::vector<uint8_t> out;
    out.reserve(hex.size() / 2);
    auto nibble = [](char c) -> uint8_t {
        if (c >= '0' && c <= '9') return static_cast<uint8_t>(c - '0');
        return static_cast<uint8_t>(std::tolower(static_cast<unsigned char>(c)) - 'a' + 10);
    };
    for (std::size_t i = 0; i + 1 < hex.size(); i += 2) {
        out.push_back(static_cast<uint8_t>((nibble(hex[i]) << 4) | nibble(hex[i + 1])));
    }
    return out;
}

std::string to_hex(const std::vector<uint8_t>& bytes) {
    static const char* digits = "0123456789abcdef";
    std::string s;
    s.reserve(bytes.size() * 2);
    for (uint8_t b : bytes) {
        s.push_back(digits[b >> 4]);
        s.push_back(digits[b & 0x0F]);
    }
    return s;
}

EntityId sample_reader_entity() { return EntityId{{0x00, 0x00, 0x00, 0x04}}; }
EntityId sample_writer_entity() { return EntityId{{0x00, 0x00, 0x42, 0x03}}; }
GuidPrefix sample_prefix() {
    return GuidPrefix{{0x01, 0x0f, 0x99, 0x6e, 0xca, 0xfe, 0xba, 0xbe, 0x00, 0x00, 0x00, 0x01}};
}

// Creates a fresh, uniquely-named directory under the OS temp dir for one
// test's persist_load/persist_flush round-trip, standing in for go-DDS's
// t.TempDir() (Catch2 has no built-in equivalent). Not cleaned up
// automatically — matches Go's own t.TempDir() only in spirit, not in
// cleanup guarantees, but this is test-local, disposable scratch space.
std::string make_temp_dir(const std::string& name) {
    static std::atomic<uint64_t> counter{0};
    auto path = std::filesystem::temp_directory_path() /
                ("cppdds_test_" + name + "_" + std::to_string(counter.fetch_add(1)) + "_" +
                 std::to_string(std::chrono::steady_clock::now().time_since_epoch().count()));
    std::filesystem::create_directories(path);
    return path.string();
}

