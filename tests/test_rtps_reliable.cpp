// Registers a fake remote writer (writer_prefix/writer_eid) as SEDP-matched
// to every local reader on topic_name, standing in for a peer participant
// that has already been discovered — matching the existing
// "SedpService::matched_reader_locators_for_topic filters by topic and
// dedupes" test's pattern of feeding SedpService::handle_packet directly.
void announce_fake_remote_writer(Participant& p, const GuidPrefix& writer_prefix, const EntityId& writer_eid,
                                  const std::string& topic_name, uint16_t writer_data_port) {
    auto data = build_endpoint_data(EndpointInfo{GUID{writer_prefix, writer_eid}, topic_name, true},
                                     writer_data_port);
    auto announcement = build_sedp_announcement(writer_prefix, kVendorIdCppDDS, kEntityIdSEDPPubWriter,
                                                 kEntityIdSEDPPubReader, SequenceNumber{0, 1}, data);
    p.sedp().handle_packet(announcement, "127.0.0.1");
}

// Registers a fake remote reader as SEDP-matched to a local writer on
// topic_name, with its data-receive locator pointing at reader_data_port
// (typically a raw UdpSocket standing in for the remote reader).
void announce_fake_remote_reader(Participant& p, const GuidPrefix& reader_prefix, const EntityId& reader_eid,
                                  const std::string& topic_name, uint16_t reader_data_port) {
    auto data = build_endpoint_data(EndpointInfo{GUID{reader_prefix, reader_eid}, topic_name, false},
                                     reader_data_port);
    auto announcement = build_sedp_announcement(reader_prefix, kVendorIdCppDDS, kEntityIdSEDPSubWriter,
                                                 kEntityIdSEDPSubReader, SequenceNumber{0, 1}, data);
    p.sedp().handle_packet(announcement, "127.0.0.1");
}

// Sends a DATA submessage for seq/payload, addressed as if from
// (writer_prefix, writer_eid), to dst_port on 127.0.0.1 via sock.
void send_fake_data(UdpSocket& sock, const GuidPrefix& writer_prefix, const EntityId& writer_eid, uint64_t seq,
                     const std::vector<uint8_t>& payload, int dst_port) {
    DataSubmessage ds;
    ds.reader_entity_id = kEntityIdUnknown;
    ds.writer_entity_id = writer_eid;
    ds.seq_num            = u64_to_sn(seq);
    ds.payload             = cdr_wrap_payload(payload);
    std::vector<uint8_t> submsg;
    ds.encode(submsg);
    auto msg = wrap_in_rtps_message(writer_prefix, kVendorIdCppDDS, submsg);
    sock.send_to("127.0.0.1", dst_port, msg.data(), msg.size());
}

// Polls sock for up to ~3s for a datagram whose first submessage id (at
// Header::kSize, i.e. byte 20) equals want_submessage_id.
std::optional<UdpPacket> recv_submessage(UdpSocket& sock, uint8_t want_submessage_id) {
    for (int attempt = 0; attempt < 60; ++attempt) {
        auto pkt = sock.recv();
        if (pkt && pkt->data.size() > Header::kSize && pkt->data[Header::kSize] == want_submessage_id) {
            return pkt;
        }
    }
    return std::nullopt;
}

