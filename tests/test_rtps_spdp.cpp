// `git status` in the go-DDS clone was confirmed clean afterward.
//
// Note: 192.168.1.50 = 0xC0.0xA8.0x01.0x32, which is exactly the trailing
// 4 bytes of SPDP_PROXY_META_LOCATOR/DATA_LOCATOR's address above — that's
// the from-address fill-in for the 0.0.0.0 locators buildParticipantData
// emits (it doesn't know its own externally-visible IP), asserted below.
//
// The SpdpService peer-table/eviction/self-filtering tests below are
// ordinary behavioral tests (go-DDS has no dedicated unit test isolating
// just the known-peers-table logic either — it's exercised indirectly
// through full participant integration tests, which is a later Tier-1
// phase here), not wire-format conformance vectors. The two-participant
// discovery test overrides SpdpConfig::dest_address/dest_port to target
// the peer's bound socket directly over loopback rather than the real
// SPDP multicast group/port, for the same reason test_rtps_transport.cpp's
