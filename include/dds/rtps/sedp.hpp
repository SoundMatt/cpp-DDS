// rtps/sedp.hpp — SEDP: Simple Endpoint Discovery Protocol
// (RTPS 2.3 §8.5.4 / §9.6.2). When a local writer or reader is registered,
// SEDP sends a publication or subscription announcement unicast to every
// known participant's meta-unicast port. When a remote announcement
// arrives, its topic name is matched against local endpoints so readers
// can be linked to their matching writers.
//
// This is Tier-1 sub-phase 5 of the cpp-DDS RTPS roadmap (see ROADMAP.md,
// "Tier 1 — RTPS wire protocol", phase 5: "SEDP"). It is internal,
// additive scaffolding: NOT yet wired into the public
// dds::IParticipant / relay::INode surface. That happens once entities
// (phase 6) exist to actually own reader/writer objects and a
// HistoryCache for matched data to flow into.
//
// C++ port of github.com/SoundMatt/go-DDS's rtps/sedp.go (sedpService and
// its methods). Every build_endpoint_data()/build_sedp_announcement()
// output here MUST produce byte-identical wire bytes to the corresponding
// go-DDS function for equivalent field values; see
// tests/test_rtps_sedp.cpp for the reference vectors (generated by
// literally calling go-DDS's own unexported functions white-box from a
// scratch _test.go file — not re-derived by hand) that pin this.
//
// Scope notes (deliberate deviations from a literal line-for-line port,
// matching the "internal scaffolding, no entities yet" constraint of this
// phase — the same constraint SPDP (phase 4) was built under):
//
//   - go-DDS's sedpService is a method set on the full `participant` type
//     (rtps/participant.go, 1,505 LOC — Tier-1 phase 6, not yet ported)
//     and reaches into it for exactly two things: the participant's own
//     GUID prefix/data-unicast port (to build endpoint payloads) and
//     `s.p.spdp.allPeers()` (to broadcast to every known participant).
//     This port instead takes the small, explicit slice of state SEDP
//     actually needs via SedpConfig, and maintains its own known-peers
//     table fed by explicit on_new_peer()/on_peer_evicted() calls — the
//     same shape SpdpService's own known-peers table already has —
//     rather than holding a live reference to a not-yet-ported
//     participant or a direct dependency on the SpdpService class. Phase
//     6 is expected to own a SedpService instance and wire
//     SpdpService::on_new_peer/eviction events into it, exactly as
//     go-DDS's participant type wires spdpService and sedpService
//     together internally.
//   - go-DDS's `endpointInfo` also carries `isWriter`, but nothing ever
//     reads that field back off a *received* announcement (the writer/
//     reader distinction for incoming packets is made once, up front, by
//     which SEDP writer entity ID the DATA submessage carries — see
//     handle_packet/handle_endpoint_announce). This port therefore keeps
//     `is_writer` on EndpointInfo (used for locally-registered endpoints,
//     matching go-DDS) but omits it from ParsedEndpointInfo (the decoded-
//     from-wire shape), which is a value-preserving simplification, not a
//     behavioral change.
//   - go-DDS's `sedpService.registerReader`/`onRemoteWriter` link a
//     matched writer to a reader by calling `r.addSourceGUID(rw.guid)` on
//     the not-yet-ported `rtpsReader` type, and `onRemoteWriter` also
//     registers the writer's data-delivery locator on the participant via
//     `p.addWriterLocator`. Both are replaced here with explicit query
//     tables (`matched_writer_guids_for_reader`, `writer_locator`,
//     `reader_locator`) that phase 6 can consume once rtpsReader/writer
//     equivalents exist — the matching bookkeeping itself (this phase's
//     actual deliverable) is fully ported, including the
//     `endpoint_matches` counter go-DDS increments in `onRemoteWriter`.
//   - The optional EndpointPlugin authentication-tag exchange
//     (`pidEndpointToken`) is omitted, mirroring SPDP's omission of
//     `pidDiscoveryToken`: it is Tier-2 security scope, not part of this
//     phase's "announce + topic-match" description.
//   - go-DDS's single process-wide `nextSeqNum()` atomic (shared by every
//     participant's SPDP *and* SEDP writers) is, as in SpdpService, one
//     atomic counter per SedpService instance instead — scoped to this
//     phase; a later phase can thread a shared counter through once one
//     exists to wire alongside it.
//   - Threading: only a receive loop runs in the background (go-DDS's
//     `sedpService.start()` likewise launches only `receiveLoop` — unlike
//     SPDP there is no periodic announce loop; SEDP announcements are
//     purely event-driven, fired from register_writer/register_reader/
//     on_new_peer). Uses the same cancellable-sleep-free, socket-internal-
//     timeout poll pattern as SpdpService::receive_loop.

