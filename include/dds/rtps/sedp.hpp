namespace dds::rtps {

// ── EndpointInfo ─────────────────────────────────────────────────────────────

// EndpointInfo describes a local or remote DDS endpoint. C++ port of
// go-DDS's endpointInfo (rtps/sedp.go).
struct EndpointInfo {
    GUID        guid{};
    std::string topic_name;
    bool        is_writer{false};
};

// Builds PL_CDR_LE EndpointData wire bytes for one endpoint, matching
// go-DDS's sedpService.buildEndpointData field for field. data_unicast_port
// is the participant-level user-DATA unicast port (go-DDS: p.dataSock.port)
// advertised via pidDefaultUnicastLocator — the same port for every local
// endpoint on this participant, regardless of that endpoint's own identity.
std::vector<uint8_t> build_endpoint_data(const EndpointInfo& info, uint16_t data_unicast_port);

// ParsedEndpointInfo is the decoded shape of a received EndpointData
// payload — see the file-level scope note for why it omits is_writer.
struct ParsedEndpointInfo {
    GUID        guid{};
    std::string topic_name;
    Locator     data_locator{};
};

// Parses PL_CDR_LE EndpointData received from from_address (dotted-quad
// IPv4). remote_prefix seeds guid.prefix (overwritten if a pidEndpointGUID
// parameter is present), matching go-DDS's handleEndpointAnnounce:
// `info.guid.Prefix = remotePrefix` is set before the decode loop, then
// possibly replaced by a decoded pidEndpointGUID value. A 0.0.0.0-address
// pidDefaultUnicastLocator has from_address filled into its trailing 4
// bytes, matching go-DDS's decodeLocator fill-in path (same trick
// parse_participant_data uses for SPDP). Returns std::nullopt if the
// PL_CDR_LE header itself is invalid, or if no pidTopicName parameter was
// present (go-DDS: handleEndpointAnnounce returns early when
// info.topicName == "").
std::optional<ParsedEndpointInfo> parse_endpoint_data(const GuidPrefix&   remote_prefix,
                                                        const uint8_t*      payload,
                                                        std::size_t         payload_len,
                                                        const std::string&  from_address);

// Builds the full wire bytes of one SEDP endpoint announcement: a DATA
// submessage (writer=writer_eid, reader=reader_eid, payload) wrapped in an
// RTPS message. C++ port of the construction shape shared by go-DDS's
// sedpService.announceWriter (writer_eid/reader_eid =
// kEntityIdSEDPPubWriter/kEntityIdSEDPPubReader) and .announceReader
// (kEntityIdSEDPSubWriter/kEntityIdSEDPSubReader).
std::vector<uint8_t> build_sedp_announcement(const GuidPrefix& local_prefix, const VendorId& vendor_id,
                                              const EntityId& writer_eid, const EntityId& reader_eid,
                                              SequenceNumber seq_num, const std::vector<uint8_t>& payload);

// ── SedpService ───────────────────────────────────────────────────────────────

// SedpConfig configures a SedpService instance.
struct SedpConfig {
    GuidPrefix local_guid_prefix{};
    // This participant's user-DATA unicast port, advertised in every local
    // endpoint announcement (go-DDS: p.dataSock.port).
    uint16_t data_unicast_port{0};
    VendorId vendor_id{kVendorIdCppDDS};
};

// SedpService manages local endpoint registration/announcement and the
// remote endpoint tables populated from received announcements. C++ port
// of go-DDS's sedpService (rtps/sedp.go) — see the file-level scope note
// for the deliberate deviations relative to a full line-for-line port.
class SedpService {
public:
    // socket is used both to send unicast announcements and to receive
    // them (go-DDS: p.metaSock, shared with SPDP's outbound send — see the
    // scope note in spdp.hpp about why SpdpService owns its own send
    // socket instead of literally sharing one with this class). Moved
    // into the service.
    SedpService(SedpConfig config, UdpSocket socket);
    ~SedpService();

    SedpService(const SedpService&)            = delete;
    SedpService& operator=(const SedpService&) = delete;
    SedpService(SedpService&&)                 = delete;
    SedpService& operator=(SedpService&&)      = delete;

    // Starts the receive thread. No-op if already started.
    void start();

    // Stops the receive thread and joins it. No-op if already stopped;
    // safe to call more than once and from the destructor.
    void stop();

    // Registers a local writer, records it, and immediately announces it
    // to every peer currently in the known-peers table (go-DDS:
    // registerWriter).
    void register_writer(const EntityId& eid, const std::string& topic_name);

    // Registers a local reader, records it, matches it against
    // already-discovered remote writers for the same topic (recorded in
    // matched_writer_guids_for_reader — see the file-level scope note),
    // and announces it to every known peer (go-DDS: registerReader).
    void register_reader(const EntityId& eid, const std::string& topic_name);

    // Records peer in the known-peers table and announces every currently
    // registered local endpoint to just that peer (go-DDS: onNewPeer, plus
    // the known-peers bookkeeping this port folds in — see the file-level
    // scope note). Intended to be called by phase 6's wiring whenever
    // SpdpService discovers a genuinely new participant.
    void on_new_peer(const ParticipantProxy& peer);

    // Removes peer's prefix from the known-peers table and purges all
    // remote endpoints (and their locators) belonging to it (go-DDS:
    // onPeerEvicted). Intended to be called by phase 6's wiring whenever a
    // peer's SPDP lease expires.
    void on_peer_evicted(const GuidPrefix& prefix);

    // Processes one received datagram as if it had arrived on this
    // service's socket (go-DDS: handlePacket). Called internally by the
    // receive loop; exposed so tests can drive the remote endpoint tables
    // deterministically without depending on socket timing.
    void handle_packet(const std::vector<uint8_t>& data, const std::string& from_address);

    // ── query surface for phase 6's reader/writer wiring ──────────────────

    // Snapshot of remote writer GUIDs matched to reader_eid so far (via
    // either register_reader or a later remote-writer announcement).
    std::vector<GUID> matched_writer_guids_for_reader(const EntityId& reader_eid) const;

    // Data-delivery locator for a matched remote writer, if known.
    std::optional<Locator> writer_locator(const GUID& writer_guid) const;

    // Data-delivery locator for a matched remote reader, if known.
    std::optional<Locator> reader_locator(const GUID& reader_guid) const;

    uint64_t endpoint_matches() const noexcept { return endpoint_matches_.load(); }
    uint64_t announces_sent() const noexcept { return announces_sent_.load(); }
    uint64_t announces_received() const noexcept { return announces_received_.load(); }

private:
    struct GuidPrefixHash {
        std::size_t operator()(const GuidPrefix& g) const noexcept;
    };
    struct EntityIdHash {
        std::size_t operator()(const EntityId& e) const noexcept;
    };
    struct GUIDHash {
        std::size_t operator()(const GUID& g) const noexcept;
    };

    void announce_writer(const EndpointInfo& info, const ParticipantProxy* only_to);
    void announce_reader(const EndpointInfo& info, const ParticipantProxy* only_to);
    void broadcast(const std::vector<uint8_t>& msg, const ParticipantProxy* only_to);
    void send_to(const std::vector<uint8_t>& msg, const ParticipantProxy& peer);

    void handle_endpoint_announce(const GuidPrefix& remote_prefix, const std::vector<uint8_t>& payload,
                                   bool is_writer, const std::string& from_address);
    void on_remote_writer(const EndpointInfo& info, const Locator& data_locator);
    void on_remote_reader(const EndpointInfo& info, const Locator& data_locator);

    void receive_loop();

    SedpConfig config_;
    UdpSocket  socket_;

    mutable std::mutex mu_;
    std::unordered_map<EntityId, EndpointInfo, EntityIdHash> local_writers_;
    std::unordered_map<EntityId, EndpointInfo, EntityIdHash> local_readers_;
    std::unordered_map<GUID, EndpointInfo, GUIDHash>         remote_writers_;
    std::unordered_map<GUID, EndpointInfo, GUIDHash>         remote_readers_;
    std::unordered_map<GUID, Locator, GUIDHash>               remote_writer_locs_;
    std::unordered_map<GUID, Locator, GUIDHash>               remote_reader_locs_;
    std::unordered_map<EntityId, std::vector<GUID>, EntityIdHash> matched_writers_by_reader_;
    std::unordered_map<GuidPrefix, ParticipantProxy, GuidPrefixHash> known_peers_;

    std::atomic<bool>     running_{false};
    std::atomic<uint32_t> seq_counter_{0};
    std::thread           receive_thread_;

    std::atomic<uint64_t> announces_sent_{0};
    std::atomic<uint64_t> announces_received_{0};
    std::atomic<uint64_t> endpoint_matches_{0};
};

} // namespace dds::rtps
